"""Is a backtest bias a model defect or a demand REGIME? This measures it.

    uv run python dev/regime.py

Writes a markdown report and `<figures>/_regime.png`. Reads the cached predictions;
nothing is refitted.

THE TRAP
========
A backtest with only a few folds can show every model systematically under- (or over-)
forecasting, and it is tempting to build machinery on that: a multiplier search, quantile
retraining, a hunt for the mechanism. But a few consecutive folds can all sit inside one
stretch of history where demand ran ahead of (or behind) expectation. Rerun the same
models over many more folds -- several years, several seasonal peaks -- and the average
bias can collapse toward zero. When that happens the bias did not shrink because the
models improved; it shrank because the longer window includes the stretches where demand
ran the other way. See docs/FINDINGS.md.

THE EVIDENCE IT IS DEMAND, NOT MODELLING
========================================
The test is the correlation of per-fold bias ACROSS models. If it is strongly positive
even for `croston` and `moving_average`, which share no features, no library and no code
path with the boosted trees, then estimators with almost nothing in common are wrong in
the same direction at the same time.

A defect of any one model cannot do that. A shift in the demand level can: every model is
fitted on history, so when the level moves, all of them lag it together.

WHY THIS MATTERS MORE THAN IT SOUNDS
====================================
The forecast multiplies its output by `k`, fitted on backtest folds. If the fitted window
is a negative-bias regime and the future is a positive-bias regime, the multiplier does
not merely stop helping -- it compounds the error, because it lifts a forecast that is
already running high. In a fold where every model over-forecast, a lift above 1 orders
even further past demand.

So the honest reading of the multiplier is: it corrects an average taken over a period
containing both regimes, and it is wrong in one direction for part of any given year. It
can still be worth having, but it should be monitored against realised bias
(`dev/track.py`) rather than fitted once and trusted, and never fitted on only a handful
of folds.

WHAT THIS FILE DOES NOT CLAIM
=============================
It does not explain WHY the level moves. A dozen folds is a dozen observations of a slow
swing, which is not enough to fit a cycle to, and this file deliberately does not try. It
establishes whether the swing exists, whether it is shared across models, and whether it
is larger than the average bias the corrections in this folder are aimed at.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
from pathlib import Path

import numpy as np
import polars as pl

sys.path.insert(0, str(Path(__file__).resolve().parent))

import common  # noqa: E402
from common import LAB, figures_dir, results_dir  # noqa: E402


def collect() -> pl.DataFrame:
    rows = []
    for p in sorted(glob.glob(str(results_dir() / "*.json"))):
        n = os.path.basename(p)[:-5]
        if n.startswith("_"):
            continue
        j = json.loads(Path(p).read_text())
        if "horizons" not in j:
            continue
        for h, hv in j["horizons"].items():
            for f in hv.get("folds", []):
                rows.append({"model": j["model"], "h": int(h), "fold": f["fold"],
                             "test_start": f["test_start"], "test_end": f["test_end"],
                             "wape": f["wape"], "bias": f["bias"]})
    return pl.DataFrame(rows)


def cross_model_corr(df: pl.DataFrame, h: int) -> tuple[float, int]:
    s = df.filter(pl.col("h") == h)
    models = sorted(s["model"].unique())
    piv = s.pivot(on="model", index="fold", values="bias").sort("fold")
    M = np.array([piv[m].to_numpy() for m in models if m in piv.columns], dtype=float)
    if M.shape[0] < 2 or M.shape[1] < 3:
        return float("nan"), M.shape[1]
    C = np.corrcoef(M)
    iu = np.triu_indices(C.shape[0], 1)
    return float(np.nanmean(C[iu])), M.shape[1]


def main() -> None:
    ap = argparse.ArgumentParser(description="Test whether the bias is a demand regime or a model defect.")
    ap.add_argument("--tuned", action="store_true")
    args = ap.parse_args()
    common.set_mode("tuned" if args.tuned else "initial")

    df = collect()
    if df.is_empty():
        raise SystemExit("no cached fold results")
    n_folds = df["fold"].n_unique()

    L: list[str] = []
    L.append("# Is the bias a demand regime or a model defect?\n")
    L.append(f"*Generated by `dev/regime.py` (mode `{common.MODE}`) from "
             f"`{results_dir().name}/`. Nothing was refitted.*\n")
    L.append(f"Measured over **{n_folds} rolling-origin folds**.\n")
    L.append(f"![regime]({figures_dir().name}/_regime.png)\n")

    L.append("## The headline\n")
    L.append("Average bias over a short backtest against the full one, same models, same "
             "code, same data:\n")
    old = Path("dev/results_3fold")
    if old.exists():
        L.append(f"| model | h | bias (3 folds) | bias ({n_folds} folds) |")
        L.append("|---|---|---|---|")
        for p in sorted(glob.glob(str(old / "*.json"))):
            n = os.path.basename(p)[:-5]
            if n.startswith("_"):
                continue
            j = json.loads(Path(p).read_text())
            if "horizons" not in j:
                continue
            for h in ("30", "90", "180"):
                new = df.filter((pl.col("model") == j["model"]) & (pl.col("h") == int(h)))
                if h in j["horizons"] and new.height:
                    L.append(f"| `{j['model']}` | {h} | "
                             f"{j['horizons'][h]['bias']:+.3f} | "
                             f"{float(new['bias'].mean()):+.3f} |")
        L.append("")
        L.append("If the bias shrinks, it is not because the models improved: the short "
                 "backtest sat inside one stretch of history, and the long one includes "
                 "stretches where demand ran the other way.\n")

    L.append("## Is every model wrong in the same direction at the same time?\n")
    for h in sorted(df["h"].unique()):
        r, n = cross_model_corr(df, h)
        L.append(f"- **{h} d** — mean pairwise correlation of per-fold bias across the "
                 f"models: **{r:+.3f}** (over {n} folds)")
    L.append("")
    L.append("If that correlation is strongly positive, note that it includes `croston` "
             "and `moving_average`, which share no features, no library and no code path "
             "with the boosted trees. **A defect in any one model cannot produce that. A "
             "shift in the demand level can** — every model is fitted on history, so when "
             "the level moves they all lag it together.\n")

    h = 90
    s = df.filter(pl.col("h") == h)
    piv = s.pivot(on="model", index=["fold", "test_start"], values="bias").sort("fold")
    models = [c for c in piv.columns if c not in ("fold", "test_start")]
    L.append(f"## Bias by fold at {h} days\n")
    L.append("| test window opens | " + " | ".join(f"`{m}`" for m in models) + " | mean |")
    L.append("|---" * (len(models) + 2) + "|")
    for row in piv.iter_rows(named=True):
        vals = [row[m] for m in models]
        mean = float(np.mean([v for v in vals if v is not None]))
        flag = " ⚠" if abs(mean) > 0.10 else ""
        L.append(f"| {row['test_start']}{flag} | "
                 + " | ".join(f"{v:+.3f}" if v is not None else "—" for v in vals)
                 + f" | **{mean:+.3f}** |")
    L.append("\n⚠ marks a fold where the catalogue-wide mean bias exceeds ±0.10 — i.e. "
             "every model was off by more than a tenth of total volume, together.\n")

    # the actionable risk
    means = []
    for row in piv.iter_rows(named=True):
        vals = [row[m] for m in models if row[m] is not None]
        means.append(float(np.mean(vals)))
    worst_hi = max(means)
    worst_lo = min(means)
    L.append("## What this means for the multiplier\n")
    L.append(f"The forecast multiplies its output by `k`, fitted on backtest folds. "
             f"Across the {n_folds} folds here the catalogue-wide mean bias ranges from "
             f"**{worst_lo:+.3f}** to **{worst_hi:+.3f}** at the {h}-day horizon.\n")
    L.append(f"In the worst positive fold every model already over-forecast by "
             f"{worst_hi:+.3f} on average. Applying a lift above 1 on top of that orders "
             f"further past demand — the multiplier does not merely stop helping, it "
             f"compounds the error.\n")
    L.append("So the multiplier corrects an average taken over a period containing both "
             "regimes, and is wrong in one direction for part of any given year. It can "
             "still be worth having (see `dev/debias.py` for what it is worth), but it "
             "should be **monitored against realised bias** (`dev/track.py`) rather than "
             "fitted once and trusted.\n")

    L.append("## What this does not claim\n")
    L.append(f"- **It does not explain why the level moves.** {n_folds} folds is "
             f"{n_folds} observations of a slow swing, which is not enough to fit a cycle "
             f"to, and this file does not try.\n")
    L.append("- **It does not make the models better.** The swing is in the data. A model "
             "fitted on history will always lag a level shift; the question this raises "
             "is whether anything in the feature set could lead it — a forward-looking "
             "input known early enough to cover the decision window.\n")
    L.append("- **Folds are not independent samples of a stationary process.** They are "
             "consecutive slices of one history, so 'average bias' is an average over "
             "whatever regimes happened to occur, not an estimate of a stable parameter.\n")

    path = LAB / ("REGIME.md" if common.MODE == "initial"
                  else f"REGIME_{common.MODE.upper()}.md")
    path.write_text("\n".join(L))

    # ---- figure -----------------------------------------------------------------
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, len(df["h"].unique()), figsize=(6.2 * df["h"].n_unique(), 5),
                             squeeze=False)
    for ax, hh in zip(axes[0], sorted(df["h"].unique())):
        ss = df.filter(pl.col("h") == hh)
        for m in sorted(ss["model"].unique()):
            t = ss.filter(pl.col("model") == m).sort("fold")
            ax.plot(range(1, t.height + 1), t["bias"], marker="o", ms=3.5, lw=1.3,
                    alpha=.85, label=m)
        mean_by_fold = (ss.group_by("fold").agg(b=pl.col("bias").mean()).sort("fold"))
        ax.plot(range(1, mean_by_fold.height + 1), mean_by_fold["b"], color="black",
                lw=2.6, label="mean", zorder=5)
        ax.axhline(0, color="#333", lw=1, ls="--")
        ax.set_xlabel("fold (oldest → newest)")
        ax.set_title(f"{hh} days", fontsize=11)
        ax.grid(alpha=.25)
    axes[0][0].set_ylabel("bias  (− under-forecast, + over-forecast)")
    axes[0][-1].legend(fontsize=7, frameon=False, ncol=2)
    fig.suptitle("Per-fold bias by model — does it swing together? "
                 "(if so, the driver is demand)", fontsize=12, fontweight="bold")
    fig.tight_layout()
    figures_dir().mkdir(parents=True, exist_ok=True)
    out = figures_dir() / "_regime.png"
    fig.savefig(out, dpi=130)
    plt.close(fig)

    print(f"\n{'=' * 80}\nREGIME [{common.MODE}]  {n_folds} folds\n{'=' * 80}")
    for hh in sorted(df["h"].unique()):
        r, n = cross_model_corr(df, hh)
        ss = df.filter(pl.col("h") == hh)
        mb = ss.group_by("fold").agg(b=pl.col("bias").mean())["b"]
        print(f"  h={hh:>3}  cross-model bias correlation {r:+.3f}  |  "
              f"fold mean bias spans {float(mb.min()):+.3f} .. {float(mb.max()):+.3f}  |  "
              f"average {float(mb.mean()):+.3f}")
    print(f"\nreport -> {path}\nfigure -> {out}")


if __name__ == "__main__":
    main()
